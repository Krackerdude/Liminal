"""The player, hand-pixelled, one glyph per value.

Nothing here is computed.  Every pixel's *value* is chosen in this file, so
there is no gradient anywhere in the sprite and no radial term rounding
anything off — shadows describe planes, which is the rule earlier attempts
broke worst.  The module that reads this only maps glyphs to colours.

Constructed in the stated order: silhouette, then large shapes, then
proportion, then hair, then face, then clothing.

    head + hair   rows 1..15   half the figure, and the hair carries it
    sweater       rows 16..23  narrow, straight-sided, no waist
    legs          rows 24..26  extremely short
    shoes         rows 27..29  directly beneath the body

Shape language is rectangles, trapezoids and wedges.  There is not a circle in
it.  The hair is one heavy mass with a straight brow, a wedge cut out of the
left temple and a lock hanging one row lower on the right — the asymmetry is
deliberate and it is the only asymmetry on the sprite.

The perspective is the warped pseudo-top-down one: you see two rows of the top
of the hair, one row of the tops of the shoulders and one of the tops of the
shoes, and nothing about it is geometrically correct.

Every direction is the same physical object.  Hair is sixteen wide, the head
is fifteen rows and the sweater is twelve wide in all four, so the bounding
box barely changes when the figure turns — a wooden toy rotating, not four
drawings.

Glyphs, darkest first within each material:

    .  nothing
    1 2 3 4   hair          0  eye
    5 6       skin
    7 8 9     sweater       a b   shorts
    c d       shoes
"""

