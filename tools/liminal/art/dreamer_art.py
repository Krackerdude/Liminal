STEP_ROW = 18

BASE = {"down": DOWN, "up": UP, "right": RIGHT}
STEP = {"down": DOWN_STEP, "up": UP_STEP, "right": RIGHT_STEP}


def _split(art: str) -> list[str]:
    rows = art.rstrip("\n").split("\n")
    rows += ["." * 24] * (32 - len(rows))
    return [row.ljust(24, ".")[:24] for row in rows[:32]]


def grid(facing: str, frame: int) -> list[str]:
    """The whole 24x32 cell for one facing and one frame, as rows of glyphs."""
    rows = _split(BASE[facing])
    patch = STEP[facing][frame]
    if patch is not None:
        for index, row in enumerate(_split(patch)[:12]):
            rows[STEP_ROW + index] = row
    return rows


for _name, _art in BASE.items():
    for _index, _row in enumerate(_split(_art)):
        assert len(_row) == 24, f"{_name} row {_index} is {len(_row)} wide"
