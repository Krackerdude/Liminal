def text_width(text: str, spacing: int = 1, scale: int = 1) -> int:
    if not text:
        return 0
    return (len(text) * (GLYPH_W + spacing) - spacing) * scale


def draw_text(canvas: Canvas, text: str, x: int, y: int, color: RGB, *,
              scale: int = 1, spacing: int = 1,
              shadow: RGB | None = None) -> int:
    """Stamp ``text`` and return the x coordinate just past it."""
    cursor = x
    for char in text.upper():
        rows = _FONT.get(char, _FONT[" "])
        for row_index, row in enumerate(rows):
            for col_index, cell in enumerate(row):
                if cell != "#":
                    continue
                px = cursor + col_index * scale
                py = y + row_index * scale
                if shadow is not None:
                    canvas.rect(px + scale, py + scale, scale, scale, shadow)
                canvas.rect(px, py, scale, scale, color)
        cursor += (GLYPH_W + spacing) * scale
    return cursor


def draw_text_centered(canvas: Canvas, text: str, cy: int, color: RGB, *,
                       scale: int = 1, spacing: int = 1,
                       shadow: RGB | None = None, cx: int | None = None) -> None:
    width = text_width(text, spacing, scale)
    left = ((canvas.w - width) // 2) if cx is None else (cx - width // 2)
    draw_text(canvas, text, left, cy, color, scale=scale, spacing=spacing,
              shadow=shadow)
