def build_pink(map_id: int) -> World:
    """PINK BRICK.

    theme      a building that is only corridors and rooms, all of it brick
    feeling    hypnosis; the comfort of somewhere you have already been
    layout     a lattice of octagonal chambers joined by three-wide corridors
    rule       every chamber looks like the last one, and one of them does not
    """
    world, cs, rng = _new("pink", map_id, 132, 124)
    m, t = world.map, cs.tiles
    fld = Field(m.width, m.height)

    # Corridor-dominant: you are almost always in a hallway, and the rooms are
    # things you glance into on the way past.  That is what makes a building
    # feel endless rather than merely large.
    rooms = layout.warren(fld, rng, halls=14, cells_per_hall=5,
                          cell_size=(13, 11), hall_width=3)
    # Second constraint: compression.  Narrow halls open without warning into
    # something stadium-sized for one screen, then close again.
    blowouts = layout.compress(fld, rng, rooms, blowouts=5, size=(34, 28))
    rooms += blowouts
    hall_start = (rooms[0].cx, rooms[0].cy)
    # Rooms embedded in the brick that can be seen and never entered.
    sealed = layout.glimpsed_rooms(fld, rng, count=16, size=(9, 7))
    fld.ensure_connected()
    fld.protect_chokepoints()
    fld.build_walls(3)
    layout.seal_off(fld, sealed, thickness=2)
    layout.paint(m, fld, t, rng=rng)
    layout.shade_walls(m, fld, t)
    for zone in sealed:
        layout.carpet(m, fld, zone, t, rng, "full")

    # Each chamber gets one thing in the middle, and nothing else.
    for index, zone in enumerate(rooms):
        if index % 3 == 0:
            gen.stamp_centered(m, cs.obj("arch"), zone.cx, zone.cy)
        elif index % 3 == 1:
            for spot in layout.zone_spots(fld, zone, rng, 2, w=1, h=3, pad=1):
                gen.stamp(m, cs.obj("column"), *spot)
        else:
            gen.stamp_centered(m, cs.obj("niche"), zone.cx, zone.cy)

    world.plan = fld
    world.landmarks = {"rooms": [(z.cx, z.cy) for z in rooms],
                       "hall": [hall_start]}
    world.spawn = (rooms[0].cx, rooms[0].cy)
    world.npcs = ["measurer", "brick_child"]
    return world


def build_numbers(map_id: int) -> World:
    """COUNTING.

    theme      a landscape assembled out of digits, at monument scale
    feeling    being audited by something that has forgotten what it counts
    layout     stepped terraces in a black void, joined end to end in a ring
    rule       every terrace carries one number, and the numbers do not add up
    """
    world, cs, rng = _new("numbers", map_id, 150, 138)
    m, t = world.map, cs.tiles
    fld = Field(m.width, m.height)

    shelves = layout.terraces(fld, rng, count=22, size=(24, 15),
                              corridor_width=3)
    fld.ensure_connected()
    fld.protect_chokepoints()
    fld.build_walls(3)
    layout.paint(m, fld, t, rng=rng)
    layout.shade_walls(m, fld, t)

    digits = [cs.obj(f"digit_{d}") for d in (0, 1, 3, 5, 7, 9)]
    signs = [cs.obj(f"sign_{k}") for k in ("plus", "minus", "equals")]
    # Second constraint: every terrace is made of a different material.  The
    # shape repeats; the substance never does, so crossing one is an event.
    materials = ["full", "checker", "lattice", "rings", "stripe", "corners",
                 "cross", "border"]
    for index, zone in enumerate(shelves):
        layout.carpet(m, fld, zone, t, rng, materials[index % len(materials)])
        run = rng.randint(2, 3)
        base_x = zone.cx - (run * 4) // 2
        base_y = zone.cy - 3
        for step in range(run):
            gx = base_x + step * 4
            if not fld.open_space(gx, base_y, 3, 6, 0):
                continue
            gen.stamp(m, cs.obj("plinth"), gx, base_y + 4)
            gen.stamp(m, digits[rng.randrange(len(digits))], gx, base_y)
            if step < run - 1:
                gen.stamp(m, signs[rng.randrange(len(signs))], gx + 3,
                          base_y + 2)

    world.plan = fld
    world.landmarks = {"terraces": [(z.cx, z.cy) for z in shelves]}
    world.spawn = (shelves[0].cx, shelves[0].cy + 5)
    world.npcs = ["counter", "zero"]
    return world


def build_blocks(map_id: int) -> World:
    """THE NURSERY.

    theme      a city built out of children's blocks, at city scale
    feeling    playing in a room you have grown too big for
    layout     rectangular yards in a grid, walled with stacked block ends
    rule       the blocks are architecture, and one of them is the wrong size
    """
    world, cs, rng = _new("blocks", map_id, 146, 130)
    m, t = world.map, cs.tiles
    fld = Field(m.width, m.height)

    # Slabs floating in nothing, joined by narrow bridges: the gaps are the
    # point, because you can see where you are going long before you can work
    # out how to get there.
    yards = layout.platforms(fld, rng, count=28, size=(15, 13), bridge=3,
                             shape="rect")
    # Second constraint: no two slabs share a geometry, so the world reads as
    # twenty-eight decisions rather than one rule applied twenty-eight times.
    layout.vary_zones(yards, rng)
    for zone in yards:
        fld.carve(zone)
    fld.ensure_connected()
    fld.protect_chokepoints()
    fld.build_walls(3)
    layout.paint(m, fld, t, rng=rng)
    layout.shade_walls(m, fld, t)

    blocks = [cs.obj(f"block_{i}") for i in range(4)]
    # Scale refuses to settle: some yards are furnished as toy rooms, some as
    # a single enormous object, some are left almost bare.
    for index, zone in enumerate(yards):
        layout.carpet(m, fld, zone, t, rng,
                      ("full", "checker", "rings", "lattice",
                       "border")[index % 5])
        # a tower in the middle of the yard, and small blocks around the edge
        stack = rng.randint(1, 3)
        for level in range(stack):
            gen.stamp(m, blocks[rng.randrange(4)], zone.cx - 1,
                      zone.cy - 1 + level * 3)
        for spot in layout.zone_spots(fld, zone, rng, 5, w=1, h=1, pad=1):
            gen.stamp(m, cs.obj("block_tiny"), *spot)
        for spot in layout.zone_spots(fld, zone, rng, 2, w=2, h=2, pad=1):
            gen.stamp(m, cs.obj("ball"), *spot)
        layout.glow_floor(m, fld, zone, t, f"anim_{index % 3}",
                          ring(zone, 5, inset=3))

    big = yards[len(yards) // 2]
    gen.stamp(m, cs.obj("block_huge"), big.cx - 2, big.cy - 2)

    world.plan = fld
    world.landmarks = {"yards": [(z.cx, z.cy) for z in yards],
                       "huge": [(big.cx, big.cy)]}
    world.spawn = (yards[0].cx, yards[0].cy + 5)
    world.npcs = ["stacker", "block_cat"]
    return world


