@dataclass
class World:
    """One generated place, ready to have events hung on it."""
    key: str
    title: str
    map_id: int
    chipset_id: int
    chipset: ChipsetBuild
    map: Map
    music: str
    spawn: tuple[int, int]
    placer: Placer
    landmarks: dict[str, list[tuple[int, int]]] = field(default_factory=dict)
    tint: tuple[int, int, int, int] = (100, 100, 100, 100)
    overlay: str | None = None
    overlay_opacity: int = 0
    npcs: list[str] = field(default_factory=list)
    plan: object | None = None    # the carved layout, for events
    rooms: list = field(default_factory=list)

    def spot(self, rng: random.Random, **kwargs) -> tuple[int, int]:
        return gen.free_spot(self.map, self.placer, rng, **kwargs)


