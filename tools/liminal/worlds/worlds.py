def build_stars(map_id: int) -> World:
    """THE SHALLOWS.

    theme      an ocean of stars with a few boards laid across it
    feeling    walking on something that should not hold your weight
    layout     islands strung on a long pier, everything else unwalkable
    rule       leaving the boards is not possible, and the water is the sky
    """
    world, cs, rng = _new("stars", map_id, 144, 132)
    m, t = world.map, cs.tiles
    fld = Field(m.width, m.height)

    islands = layout.archipelago(fld, rng, islands=24, size=(15, 12), pier=3)
    # Second constraint: the islands are not variations on an island.  Each is
    # a different kind of place that happens to be surrounded by water.
    layout.vary_zones(islands, rng)
    for zone in islands:
        fld.carve(zone)
    centre = fld.carve(Zone("centre", m.width // 2, m.height // 2, 21, 15,
                            "round"))
    for zone in islands[::2]:
        fld.corridor((centre.cx, centre.cy), (zone.cx, zone.cy), width=3)
    fld.ensure_connected()
    fld.protect_chokepoints()
    fld.build_walls(2)
    layout.paint(m, fld, t, rng=rng)
    layout.shade_walls(m, fld, t)

    for index, zone in enumerate(islands):
        layout.carpet(m, fld, zone, t, rng,
                      ("rings", "full", "lattice", "corners")[index % 4])
        layout.glow_floor(m, fld, zone, t, "flow", ring(zone, 5, inset=3))
        gen.stamp(m, cs.obj("pier"), zone.cx - 2, zone.cy + 3)
        if index % 2 == 0:
            gen.stamp(m, cs.obj("lamp"), zone.cx + 5, zone.cy - 3)
        else:
            gen.stamp(m, cs.obj("pole"), zone.cx - 1, zone.cy - 4)
        for spot in layout.zone_spots(fld, zone, rng, 1, w=1, h=2, pad=1):
            gen.stamp(m, cs.obj("buoy"), *spot)
    gen.stamp_centered(m, cs.obj("island"), centre.cx, centre.cy)

    world.plan = fld
    world.landmarks = {"islands": [(z.cx, z.cy) for z in islands],
                       "centre": [(centre.cx, centre.cy)]}
    world.spawn = (islands[0].cx, islands[0].cy)
    world.npcs = ["ferryman", "lantern_bearer"]
    return world


