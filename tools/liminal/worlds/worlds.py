"""The dreams themselves.

Fourteen places, each generated by its own algorithm because each is built out
of a different idea.  The pink world is a maze; the number world is a
scattering of monuments; the star ocean is mostly impassable and has to have
its walkable parts drawn as a network.  Sharing one generator between them
would make them feel like one game with fourteen skins, which is the failure
mode this whole project is trying to avoid.

Common rules, applied everywhere:

* the map loops on both axes
* landmarks are few and far apart, and the space between them is empty
* nothing is placed against an invisible border, because there isn't one
"""

